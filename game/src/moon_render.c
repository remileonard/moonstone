void render_text(uint32_t *fb, const char *text, int x, int y, uint32_t color)
{
    if (!text || !fb) return;
    int cx = x;
    for (const char *p = text; *p; p++) {
        unsigned char ch = (unsigned char)*p;
        if (ch == '\n') { cx = x; y += 8; continue; }
        if (ch < 0x20 || ch > 0x7F) { cx += 8; continue; }
        const uint8_t *glyph = s_font8x8[ch - 0x20];
        for (int row = 0; row < 8; row++) {
            int dy = y + row;
            if (dy < 0 || dy >= SCREEN_H) continue;
            uint8_t bits = glyph[row];
            for (int col = 0; col < 8; col++) {
                if (!(bits & (0x01 << col))) continue;
                int dx = cx + col;
                if (dx < 0 || dx >= SCREEN_W) continue;
                fb[dy * SCREEN_W + dx] = color;
            }
        }
        cx += 8;
    }
}

void render_text_centered(uint32_t *fb, const char *text, int y, uint32_t color)
{
    if (!text) return;
    int len = 0;
    for (const char *p = text; *p; p++) len++;
    int x = (SCREEN_W - len * 8) / 2;
    render_text(fb, text, x, y, color);
}

/* ------------------------------------------------------------------ */
/* Vertical scroll                                                     */
/* ------------------------------------------------------------------ */

void render_scroll_vertical(const uint32_t *buf0,
                            const uint32_t *buf1,
                            const uint32_t *buf2,
                            uint32_t *fb,
                            int scroll_y)
{
    if (scroll_y < 0)   scroll_y = 0;
    if (scroll_y > 399) scroll_y = 399;

    for (int row = 0; row < SCREEN_H; row++) {
        int src_row = scroll_y + row;
        const uint32_t *src;
        int src_y;
        if (src_row < SCREEN_H) {
            src = buf0; src_y = src_row;
        } else if (src_row < 2 * SCREEN_H) {
            src = buf1; src_y = src_row - SCREEN_H;
        } else {
            src = buf2; src_y = src_row - 2 * SCREEN_H;
        }
        if (src_y >= SCREEN_H) src_y = SCREEN_H - 1;
        memcpy(fb + row * SCREEN_W,
               src + src_y * SCREEN_W,
               (size_t)SCREEN_W * sizeof(uint32_t));
    }
}
