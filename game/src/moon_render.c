/* PIV background                                                      */
/* ------------------------------------------------------------------ */

/* Extract planar pixel index from a PIV bitmap */
static int piv_get_pixel(const MoonPiv *piv, int x, int y)
{
    int row_bytes = ((piv->width + 15) / 16) * 2;
    int pixel_idx = 0;
    for (int pl = 0; pl < piv->planes; pl++) {
        size_t byte_off = (size_t)pl  * (size_t)piv->height * (size_t)row_bytes
                        + (size_t)y   * (size_t)row_bytes
                        + (size_t)(x / 8);
        int bit = (piv->bitmap[byte_off] >> (7 - (x % 8))) & 1;
        pixel_idx |= (bit << pl);
    }
    return pixel_idx;
}

void render_piv(const MoonPiv *piv,
                uint32_t *fb,
                int dst_x, int dst_y,
                int src_x, int src_y,
                int copy_w, int copy_h)
{
    if (!piv || !fb) return;

    /* Clamp copy region to source */
    if (src_x + copy_w > piv->width)  copy_w = piv->width  - src_x;
    if (src_y + copy_h > piv->height) copy_h = piv->height - src_y;
    if (copy_w <= 0 || copy_h <= 0) return;

    /* Build a local ARGB palette */
    uint32_t pal[32];
    int pal_size = 1 << piv->planes;
    if (pal_size > 32) pal_size = 32;
    for (int i = 0; i < pal_size; i++)
        pal[i] = render_amiga_color(piv->palette[i]);

    for (int row = 0; row < copy_h; row++) {
        int dy = dst_y + row;
        if (dy < 0 || dy >= SCREEN_H) continue;
        int sy = src_y + row;
        for (int col = 0; col < copy_w; col++) {
            int dx = dst_x + col;
            if (dx < 0 || dx >= SCREEN_W) continue;
            int sx  = src_x + col;
            int idx = piv_get_pixel(piv, sx, sy);
            fb[dy * SCREEN_W + dx] = pal[idx & (pal_size - 1)];
        }
    }
}

void render_piv_full(const MoonPiv *piv, uint32_t *fb)
{
    if (!piv) return;
    render_piv(piv, fb, 0, 0, 0, 0, piv->width, piv->height);
}

