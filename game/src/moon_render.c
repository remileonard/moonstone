/* CEL / OB sprite blit                                                */
/* ------------------------------------------------------------------ */

/* Extract pixel index from a CEL frame's planar data */
static int cel_get_pixel(const MoonCelFrame *fr, int x, int y)
{
    int row_bytes = (((int)fr->width + 15) / 16) * 2;
    int pixel_idx = 0;
    for (int pl = 0; pl < (int)fr->planes; pl++) {
        size_t byte_off = (size_t)pl * (size_t)fr->height * (size_t)row_bytes
                        + (size_t)y  * (size_t)row_bytes
                        + (size_t)(x / 8);
        int bit = (fr->data[byte_off] >> (7 - (x % 8))) & 1;
        pixel_idx |= (bit << pl);
    }
    return pixel_idx;
}

void render_cel_frame(const MoonCelFrame *frame,
                      const uint32_t     *palette,
                      uint32_t           *fb,
                      int dst_x, int dst_y,
                      int flags)
{
    if (!frame || !palette || !fb) return;
    int fw = (int)frame->width;
    int fh = (int)frame->height;
    int mask = (flags & BLIT_MASK) ? 1 : 0;

    for (int row = 0; row < fh; row++) {
        int src_y = (flags & BLIT_FLIP_Y) ? (fh - 1 - row) : row;
        int dy    = dst_y + row;
        if (dy < 0 || dy >= SCREEN_H) continue;

        for (int col = 0; col < fw; col++) {
            int src_x = (flags & BLIT_FLIP_X) ? (fw - 1 - col) : col;
            int dx    = dst_x + col;
            if (dx < 0 || dx >= SCREEN_W) continue;

            int idx = cel_get_pixel(frame, src_x, src_y);
            if (mask && idx == 0) continue; /* transparent */

            uint32_t color = palette[idx & (MAX_PALETTE - 1)];

            if (flags & BLIT_ADDITIVE) {
                uint32_t bg = fb[dy * SCREEN_W + dx];
                unsigned int r = ((bg >> 16) & 0xFF) + ((color >> 16) & 0xFF);
                unsigned int g = ((bg >>  8) & 0xFF) + ((color >>  8) & 0xFF);
                unsigned int b = ( bg        & 0xFF) + ( color        & 0xFF);
                if (r > 255) r = 255;
                if (g > 255) g = 255;
                if (b > 255) b = 255;
                fb[dy * SCREEN_W + dx] = 0xFF000000u
                    | ((uint32_t)r << 16) | ((uint32_t)g << 8) | (uint32_t)b;
            } else {
                fb[dy * SCREEN_W + dx] = color;
            }
        }
    }
}

void render_cel(const MoonCel  *cel,
                int             frame_idx,
                const uint32_t *palette,
                uint32_t       *fb,
                int dst_x, int dst_y,
                int flags)
{
    if (!cel || cel->frame_count == 0) return;
    if (frame_idx < 0)                  frame_idx = 0;
    if (frame_idx >= cel->frame_count)  frame_idx = cel->frame_count - 1;
    render_cel_frame(&cel->frames[frame_idx], palette, fb, dst_x, dst_y, flags);
}

