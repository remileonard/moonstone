/* ------------------------------------------------------------------ */
/* Palette helpers                                                     */
/* ------------------------------------------------------------------ */

uint32_t render_amiga_color(uint16_t c)
{
    uint8_t r = (uint8_t)(((c >> 8) & 0xF) * 17);
    uint8_t g = (uint8_t)(((c >> 4) & 0xF) * 17);
    uint8_t b = (uint8_t)(( c       & 0xF) * 17);
    return 0xFF000000u | ((uint32_t)r << 16) | ((uint32_t)g << 8) | b;
}

void render_build_palette(const uint16_t *amiga_pal, int n, uint32_t *out)
{
    for (int i = 0; i < n; i++)
        out[i] = render_amiga_color(amiga_pal[i]);
}

void render_copy_palette(const uint32_t *src, uint32_t *dst, int n)
{
    memcpy(dst, src, (size_t)n * sizeof(uint32_t));
}

void render_blend_palette(const uint32_t *a, const uint32_t *b,
                          uint32_t *dst, int n, int t)
{
    if (t < 0)   t = 0;
    if (t > 256) t = 256;
    int s = 256 - t;
    for (int i = 0; i < n; i++) {
        uint8_t ar = (uint8_t)((a[i] >> 16) & 0xFF);
        uint8_t ag = (uint8_t)((a[i] >>  8) & 0xFF);
        uint8_t ab = (uint8_t)( a[i]        & 0xFF);
        uint8_t br = (uint8_t)((b[i] >> 16) & 0xFF);
        uint8_t bg = (uint8_t)((b[i] >>  8) & 0xFF);
        uint8_t bb = (uint8_t)( b[i]        & 0xFF);
        uint8_t r  = (uint8_t)((ar * s + br * t) >> 8);
        uint8_t g  = (uint8_t)((ag * s + bg * t) >> 8);
        uint8_t bv = (uint8_t)((ab * s + bb * t) >> 8);
        dst[i] = 0xFF000000u | ((uint32_t)r << 16) | ((uint32_t)g << 8) | bv;
    }
}

/* ------------------------------------------------------------------ */
/* Framebuffer utilities                                               */
/* ------------------------------------------------------------------ */

void render_clear(uint32_t *fb, uint32_t color)
{
    for (int i = 0; i < SCREEN_W * SCREEN_H; i++)
        fb[i] = color;
}

void render_fill_rect(uint32_t *fb, int x, int y, int w, int h, uint32_t color)
{
    for (int row = y; row < y + h; row++) {
        if (row < 0 || row >= SCREEN_H) continue;
        for (int col = x; col < x + w; col++) {
            if (col < 0 || col >= SCREEN_W) continue;
            fb[row * SCREEN_W + col] = color;
        }
    }
}

